# Telescopic cascode (Fig. 2), round 5.
#
# Round-4 post-mortem (39.996 dB, NM0 TRIODE Vds 31 mV).
#   Right branch fine: NM2 Vds 290, NM4 Vds 340 / Vov 262, NM3 Vds 613,
#   PM2 267, PM3 290 -> vout = 1.8-.267-.290 = 1.243; t + Vds4 + Vds3 =
#   .290+.340+.613 = 1.243. Left node x1 = p1 - Vsd(PM1) = 1.527-.944 = 0.583,
#   NM1 pushed to Vds 262 (Vov 269). Cause: vcm_r4 = 1.25006 sits 7 mV above
#   vout (NM1 Vgs .959 vs NM4 Vgs .952 at the same 13.1 uA). x1 is the
#   un-fed-back output of the pair: dx1/dvcm ~ -gm1*R_left = -86.4u*11M ~
#   -950 V/V, so the +7 mV (~ +600 nA equivalent) drove x1 0.66 V down until
#   NM0 left saturation and NM1's own gds absorbed it. With NM0 triode the
#   left NMOS stack impedance collapses, i1 -> 0, the pair stops acting
#   differentially and loop gain falls to ~gds2*Rout (~40 dB). So the 13 dB
#   "over-prediction" is the bias failure, not a gain-model error: the gain
#   margin rule is not applied; the headroom (vcm trim) is fixed first.
#   The round-4 model erred because it predicted t (NM2) and Vgs4 absolutely
#   (t .2952 vs .2904 measured, Vov4 .2646 vs .262). Round 5 instead trims
#   RELATIVE to the measured state: every current, width and V1..V4 are
#   bit-identical to round 4; only vcm moves by a few mV, and every shift is
#   a small perturbation of measured numbers.
#
# (1) Device roles
#   NM2 tail sink (V4 0.815). NM1 (vin1 = vcm) / NM4 (vin2, inverting,
#   drives vout) input pair. NM0/NM3 NMOS cascodes (V3). PM1/PM3 PMOS
#   cascodes (V2). PM0/PM2 PMOS current loads (V1). x1 = left output, no
#   feedback; vout fed back to vin2 in the bench.
#
# (2) Device constraints / classification
#   NM4: INDEPENDENT, W = 2 I L/(muCox Vov^2) = 2*13.05u*.5u/(246u*.262^2)
#        = 0.77 um (kept; its Vgs is now measured), L 0.5 um, m 1.
#   NM1: MATCHED to NM4 (0.77/0.5 x1) - required so NM4's measured Vgs is
#        NM1's Vgs at the same Id/Vds (no extrapolation).
#   Branch currents fixed by V1 (13.05 uA) and V4 (26.1 uA), unchanged.
#
# (3) Signal path
#   vin2 -> gm4 -> n2 (1/(gm3+gmb3)) -> NM3 -> vout (Rn || Rp || CL).
#   Tail node: DM virtual ground, CM part degenerated by gds2. Left branch
#   returns i1 = -Gs*vt*Rn/(Rn+Rp) to the tail. Non-dominant poles n2, p2
#   ~0.65-1.1 GHz.
#
# (4) Design equations (symbolic)
#   ro = 1/(lambda Id); Rn = ro4+ro3+(gm3+gmb3) ro3 ro4;
#   Rp = ro2+ro3p+(gm3p+gmb3p) ro3p ro2; Rout = Rn||Rp; k = Rn/(Rn+Rp)
#   Tail KCL (Gs = gm4(1+eta4)): k gm4 v = (2 k Gs + gds2) vt
#   A = (gm4 - Gs vt/v) Rout;   GBW = (gm4 - Gs vt/v)/(2 pi CL)
#   PM = 90 - atan(GBW/f_n2) - atan(GBW/f_p2);  P = VDD*I_tail
#   Balance (x1 in sat): I_tail(t) = I_P0 + I_P2; I_P0 - I_P2 = (vout-x1)/Rpl
#   vcm = t + Vgs1(I_P0, Vds1);  x1 - x1_bal = -gm1 R_left (vcm - vcm_bal)
#   Numbers (measured lam/gm, Id 13.05 uA):
#     ro4 206k, ro3 503k, gm3+gmb3 = 218.4u*1.163 = 254u -> Rn 27.0 M
#     ro2 274k, ro3p 319k, gm3p+gmb3p = 138u*1.226 = 169u -> Rp 15.4 M
#     Rout 9.79 M, k .637, gds2 = .3376*26.1u = 8.81u, Gs 102.5u
#     vt/v = .637*86.39u/(1.274*102.5u+8.81u) = .395
#     Geff = 86.39u - 102.5u*.395 = 45.9u -> A = 449 = 53.05 dB
#     GBW = 45.9u/(2 pi 20p) = 0.365 MHz; PM ~ 89.9 deg; P = 47.0 uW
#
# (5) DC bias verification (vcm 1.2415, t 0.2891, vout 1.2408)
#   NM2: Vds .2891 >= Vov .182 (slack 107 mV)
#   NM4: Vds .630-.2891 = .3409 >= Vov .262 (slack 79 mV); NM1 Vds .3394,
#        Vov .2622 (slack 77 mV)
#   NM3: Vds 1.2408-.630 = .611 >= .055 (slack 556 mV)
#   PM3: Vsd 1.533-1.2408 = .292 >= .136 (156 mV); PM2/PM0 Vsd .267-.269 >=
#        .137 (130 mV)
#   x1 window: NM0 edge x1 > n1+Vov0+~.02 = .630+.055+.02 = .705;
#     PM1 edge x1 < p1-Vov_p1-.02 = 1.531-.131-.02 = 1.380; centre 1.043
#     -> NM0 Vds .413 (slack 358), PM1 Vsd .488 (slack 357). Tolerance on
#     vcm: +-0.34 V/950 = +-0.36 mV (hence the relative trim below).
#
# (6) DC operating-point consistency (all from measured round-4 numbers)
#   t_m: NM2 Vds 290 (+-.5) and vcm_r4 - (Vth1+Vov1) = 1.25006-.959 = .2911
#     (+-.7): inverse-variance mean t_m = 0.29035 V.
#   Vgs4_m: Vth+Vov = .952; Vds4+Vds3 = .953; (1.8-.267-.290)-t_m = .95265
#     -> mean 0.95253 V.
#   PMOS imbalance: measured p2-p1 = 273-267 = 6 mV at x1-vout = -.660 ->
#     PM1 cascode gain ~110; at target x1-vout = -.198 with PM1 Vsd .488
#     (gain ~70): p2-p1 = 2.8 mV -> I_P0-I_P2 = 3.49u*2.8m = 9.9 nA vs 20.9
#     nA measured -> I_tail must fall 11.0 nA -> t = .29035 - 11.0n/8.81u
#     = 0.28910 V.
#   Vgs4: body dVth = .187*(-1.25 mV) = -.23 mV; Vds4 +1.25 mV -> dVov =
#     -.3717*1.25m*13.05u/86.39u = -.07 mV -> Vgs4 = .95253-.00030 = .95223
#     vout = t + Vgs4 = .28910+.95223 = 1.24133 ... (PM3 Vsd .2917, I_P2
#     change 0.1 nA, ignored).
#   Vgs1: I1 = I4 + 9.9 nA -> +9.9n/86.39u = +.11 mV; n1 = n2 - .198/128 =
#     n2 - 1.5 mV -> +.3717*1.5m*13.05u/86.39u = +.08 mV -> Vgs1 = .95242
#   vcm = t + Vgs1 = .28910 + .95242 = 1.24152 V  (r4: 1.25006, -8.5 mV)
#   Check vs collapsed r4 state: NM1 then had Vgs .9597 at Vds .262; now
#   .9524 at Vds .339 = NM4's measured Vgs at Vds .340: consistent.
#   Loop: vin2 = vout = 1.2413, I4 = I_P2 = 13.05u, I1 = 13.06u, I_tail =
#   26.11u = NM2 at Vds .2891.
#
# (7) Python code below.
# ============================================================================
import math

VDD_DEFAULT = 1.8
L0 = 0.5e-6
PHI2 = 0.8
GAMMA_N = 0.39
GAMMA_P = 0.467

# Round-4 inputs, kept bit-identical (currents and cascode biases unchanged)
V1_R4 = 0.6706177243903462
V2_R4 = 0.3404573706044404
V3_R4 = 1.4391487805453098
V4_R4 = 0.815
W_R4 = 0.77e-6
VCM_R4 = 1.250058554064084

# Round-4 measured operating point (volts, amps, siemens)
I_BR = 13.05e-6
MEAS = dict(
    t_nm2=0.290, vth1=0.690, vov1=0.269, vth4=0.690, vov4=0.262,
    vds4=0.340, vds3=0.613, vsd_p0=0.273, vsd_p2=0.267, vsd_p3=0.290,
    gm4=86.39e-6, gm3=218.4e-6, gm3p=138.0e-6, id2=26.1e-6,
    lam4=0.3717, lam3=0.1524, lam2=0.2793, lam3p=0.2399, lam2n=0.3376,
    lam_p0=0.2665, x1_m=1.8 - 0.273 - 0.944,
)


def initial_params():
    n = {"type": "NMOS", "muCox": 270e-6, "a_gm": 1.0, "lam": 0.20, "vth": 0.69}
    p = {"type": "PMOS", "muCox": 100e-6, "a_gm": 1.0, "lam": 0.25, "vth": 1.0}
    out = {}
    for d in ("NM0", "NM1", "NM2", "NM3", "NM4"):
        out[d] = dict(n)
    for d in ("PM0", "PM1", "PM2", "PM3"):
        out[d] = dict(p)
    return out


def _p(params, dev, key, default, lo, hi):
    try:
        v = float(params[dev][key])
    except (KeyError, TypeError, ValueError):
        return default
    return v if lo <= v <= hi else default


def compute_sizing(spec, params):
    cond = spec.get("conditions", {}) if isinstance(spec, dict) else {}
    vdd = cond.get("vdd") or VDD_DEFAULT
    cl = cond.get("cl") or 20e-12
    params = params if isinstance(params, dict) else {}
    m = dict(MEAS)
    m["lam4"] = _p(params, "NM4", "lam", m["lam4"], 0.05, 2.0)
    m["lam3"] = _p(params, "NM3", "lam", m["lam3"], 0.02, 1.0)
    m["lam2"] = _p(params, "PM2", "lam", m["lam2"], 0.05, 1.0)
    m["lam3p"] = _p(params, "PM3", "lam", m["lam3p"], 0.05, 1.0)
    m["lam2n"] = _p(params, "NM2", "lam", m["lam2n"], 0.05, 1.0)
    m["lam_p0"] = _p(params, "PM0", "lam", m["lam_p0"], 0.05, 1.0)

    gm4 = m["gm4"]
    gds2 = m["lam2n"] * m["id2"]
    gds_p0 = m["lam_p0"] * I_BR

    # --- measured tail and Vgs4 (inverse-variance merge of redundant data)
    t_a, var_a = m["t_nm2"], 0.29 ** 2
    t_b, var_b = VCM_R4 - (m["vth1"] + m["vov1"]), 0.41 ** 2
    t_m = (t_a / var_a + t_b / var_b) / (1 / var_a + 1 / var_b)
    vgs4_ests = [m["vth4"] + m["vov4"], m["vds4"] + m["vds3"],
                 (vdd - m["vsd_p2"] - m["vsd_p3"]) - t_m]
    vgs4_m = (vgs4_ests[0] + vgs4_ests[1] + 0.75 * vgs4_ests[2]) / 2.75
    vout_m = t_m + vgs4_m
    n2 = t_m + m["vds4"]
    p2 = vdd - m["vsd_p2"]

    # --- x1 window and centre (5)
    vov0, vov_p1, guard = 0.055, 0.131, 0.02
    x1_lo = n2 + vov0 + guard
    x1_hi = (p2 - 0.002) - vov_p1 - guard
    x1_c = 0.5 * (x1_lo + x1_hi)

    # --- PMOS imbalance at the centred x1 (6)
    dI_m = gds_p0 * (m["vsd_p0"] - m["vsd_p2"])            # 20.9 nA
    a_p1_m = (vout_m - m["x1_m"]) / (m["vsd_p0"] - m["vsd_p2"])
    a_p1 = a_p1_m * 0.64                                    # PM1 at Vsd .49
    dI_t = gds_p0 * (vout_m - x1_c) / a_p1
    t = t_m - (dI_m - dI_t) / gds2

    eta4 = GAMMA_N / (2 * math.sqrt(PHI2 + t))
    dt = t - t_m
    vgs4 = vgs4_m + eta4 * dt - m["lam4"] * (-dt) * I_BR / gm4
    vout = t + vgs4
    a_n0 = m["gm3"] * (1 + GAMMA_N / (2 * math.sqrt(PHI2 + n2))) / (m["lam3"] * I_BR)
    dn1 = (vout - x1_c) / a_n0
    vgs1 = vgs4 + dI_t / gm4 + m["lam4"] * dn1 * I_BR / gm4
    vcm = t + vgs1

    # --- small-signal (4)
    eta3 = GAMMA_N / (2 * math.sqrt(PHI2 + n2))
    etap = GAMMA_P / (2 * math.sqrt(PHI2 + m["vsd_p2"]))
    ro4 = 1 / (m["lam4"] * I_BR)
    ro3 = 1 / (m["lam3"] * I_BR)
    ro2 = 1 / (m["lam2"] * I_BR)
    ro3p = 1 / (m["lam3p"] * I_BR)
    Rn = ro4 + ro3 + m["gm3"] * (1 + eta3) * ro3 * ro4
    Rp = ro2 + ro3p + m["gm3p"] * (1 + etap) * ro3p * ro2
    Rout = Rn * Rp / (Rn + Rp)
    k = Rn / (Rn + Rp)
    Gs = gm4 * (1 + eta4)
    vt_ratio = k * gm4 / (2 * k * Gs + gds2)
    geff = gm4 - Gs * vt_ratio
    A = geff * Rout
    gain_db = 20 * math.log10(A)
    gbw = geff / (2 * math.pi * cl)
    cox = 8.5e-3
    c_n2 = (2 / 3) * 6e-6 * L0 * cox + 1e-9 * (6e-6 + W_R4) * 2 + 0.5e-15 * W_R4 * 1e6
    c_p2 = (2 / 3) * 7e-6 * L0 * cox + 2e-9 * 7e-6
    f_n2 = m["gm3"] * (1 + eta3) / (2 * math.pi * c_n2)
    f_p2 = m["gm3p"] * (1 + etap) / (2 * math.pi * c_p2)
    pm = 90 - math.degrees(math.atan(gbw / f_n2)) - math.degrees(math.atan(gbw / f_p2))
    i_tail = 2 * I_BR + dI_t

    compute_sizing.debug = dict(
        t_m=t_m, vgs4_m=vgs4_m, vout_m=vout_m, n2=n2, x1_lo=x1_lo, x1_hi=x1_hi,
        x1_c=x1_c, dI_m=dI_m, dI_t=dI_t, a_p1=a_p1, t=t, vgs4=vgs4, vout=vout,
        vgs1=vgs1, vcm=vcm, dvcm_mV=(vcm - VCM_R4) * 1e3, Rn=Rn, Rp=Rp,
        Rout=Rout, k=k, vt_ratio=vt_ratio, geff=geff, A=A, f_n2=f_n2, f_p2=f_p2)

    return {
        "sizes": {"NM1": {"w": W_R4, "l": L0, "m": 1},
                  "NM4": {"w": W_R4, "l": L0, "m": 1}},
        "biases": {"V1": V1_R4, "V2": V2_R4, "V3": V3_R4, "V4": V4_R4},
        "currents": {},
        "caps": {},
        "vcm": vcm,
        "predicted": {"gain_dB": gain_db, "gbw_Hz": gbw, "pm_deg": pm,
                      "power_W": vdd * i_tail},
    }


