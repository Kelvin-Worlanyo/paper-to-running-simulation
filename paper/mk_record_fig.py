"""Figure: what the agent reads, beside part of the record it writes.

Panel (a) is our own redrawing of the input pair as paper A prints it, with the
paper's printed annotations reproduced verbatim; the paper's own figure is not
reprinted. Panel (b) is generated from the case files, so it cannot drift from
what the pipeline produced. Writes record_fig.tex.
"""
import json
import os
import textwrap

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
CASE, KEY, DEVICE = "opamp3", "twostage", "NM0"
WIDTH = 60                      # characters that fit the verbatim column
ZOOM = (320, 560, 640, 720)     # the input pair of the crop, where the sizes are printed


def q(x):
    return json.dumps(x, separators=(", ", ": "))


def wrapped(prefix, text, indent):
    """A JSON fragment over as many lines as the column allows."""
    first = textwrap.wrap(prefix + text, WIDTH, subsequent_indent=" " * indent,
                          break_long_words=False, break_on_hyphens=False)
    return first


def record_lines(rec):
    dev = next(d for d in rec["ckt_netlist"] if d["id"] == DEVICE)
    ab = rec["absent"][0]
    ev = dev["evidence"]
    out = ["{"]
    out += wrapped(' "pins": ', q(rec["pins"]) + ",", 10)
    out.append(' "ckt_netlist": [')
    out.append('  {"id": "%s", "role": "%s", "component_type": "%s",' % (dev["id"], dev["role"], dev["component_type"]))
    out += wrapped('   "port_connection": ', q(dev["port_connection"]) + ",", 6)
    out += ['   "size": ' + q(dev["size"]) + ",",
            '   "evidence": {"w": ' + q(ev["w"]) + ","]
    out.append("                " + q("l") + ": " + q(ev["l"]) + ", ...")
    out[-1] = out[-1].rstrip(",") + "}},"
    out.append("  ... ],")
    out.append(' "absent": [{"item": ' + q(ab["item"]) + ',')
    out.append('             "why": "printed as the symbol \'vdc=VCM\'"}]')
    out.append("}")
    return out



# our own drawing of the input pair, with the annotations the paper prints
SCHEMATIC = r"""\begin{circuitikz}[scale=0.82, transform shape, font=\scriptsize,
    every node/.style={inner sep=1pt}]
  \draw (0,0) node[nmos, rotate=0] (M1) {};
  \draw (3.6,0) node[nmos, xscale=-1] (M2) {};
  % gates
  \draw (M1.G) -- ++(-0.7,0) node[left] {\texttt{vin1}};
  \draw (M2.G) -- ++(0.7,0) node[right] {\texttt{vin2}};
  % drains up
  \draw (M1.D) -- ++(0,0.75) node[above] {\texttt{A}};
  \draw (M2.D) -- ++(0,0.75) node[above] {\texttt{B}};
  % sources joined below
  \draw (M1.S) -- ++(0,-0.75) coordinate (s1) -- (s1 -| M2.S) -- (M2.S);
  \draw ($(s1)!0.5!(s1 -| M2.S)$) -- ++(0,-0.4) node[below] {\texttt{C}};
  % the annotations the paper prints beside the left device
  \node[right, align=left, font=\scriptsize\ttfamily] at (0.55,0.62)
    {NM0\\ nmos1};
  \node[right, align=left, font=\scriptsize\ttfamily] at (0.55,-0.45)
    {w=4u\\ l=500n\\ m:1};
\end{circuitikz}"""

CAPTION = (
    "What the reading step produces, for the input pair of paper~A's two-stage amplifier. "
    "(a) is redrawn by us, with the annotations the paper prints kept verbatim. Every number in "
    "the record carries the evidence it came from, and what the figure leaves symbolic is recorded "
    "as absent rather than guessed, to be filled later by a stated policy and reported as a "
    "deviation.")


def main():
    rec = json.load(open(os.path.join(ROOT, "cases", CASE, "records", KEY + ".json")))
    lines = record_lines(rec)
    long = [l for l in lines if len(l) > WIDTH + 4]
    assert not long, long
    with open(os.path.join(HERE, "record_fig.tex"), "w") as fh:
        fh.write("% generated by mk_record_fig.py -- do not edit\n")
        fh.write("\\begin{figure}[t]\n\\centering\n")
        fh.write(SCHEMATIC + "\\\\[2pt]\n")
        fh.write("{\\footnotesize (a) the input pair as the paper draws it, redrawn}\\\\[4pt]\n")
        fh.write("\\begin{minipage}{\\columnwidth}\n\\tiny\n\\begin{verbatim}\n")
        fh.write("\n".join(lines) + "\n")
        fh.write("\\end{verbatim}\n\\end{minipage}\\\\[-2pt]\n")
        fh.write("{\\footnotesize (b) part of the circuit record it writes}\n")
        fh.write("\\caption{" + CAPTION + "}\n\\label{fig:record}\n\\end{figure}\n")
    print("wrote record_fig.tex (%d lines of record)" % len(lines))


if __name__ == "__main__":
    main()
